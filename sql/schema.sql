CREATE TABLE teams(
    season                TEXT NOT NULL,
    id                    INTEGER NOT NULL,
    code                  INTEGER,
    name                  TEXT NOT NULL,
    short_name            TEXT NOT NULL,
    strength              INTEGER,
    strength_overall_home INTEGER,
    strength_overall_away INTEGER,
    strength_attack_home  INTEGER,
    strength_attack_away  INTEGER,
    strength_defence_home INTEGER,
    strength_defence_away INTEGER,
    PRIMARY KEY (season, id)
);

CREATE TABLE positions(
    id                    INTEGER PRIMARY KEY,
    plural_name           TEXT NOT NULL,
    plural_name_short     TEXT NOT NULL,
    singular_name         TEXT NOT NULL,
    singular_name_short   TEXT NOT NULL,
    squad_select          INTEGER NOT NULL,
    squad_min_play        INTEGER NOT NULL,
    squad_max_play        INTEGER NOT NULL
);

CREATE TABLE fixtures(
    season                TEXT NOT NULL,
    id                    INTEGER NOT NULL,
    event                 INTEGER,
    kickoff_time          TEXT,
    team_h                INTEGER NOT NULL,
    team_a                INTEGER NOT NULL,
    finished              INTEGER,
    PRIMARY KEY (season, id),
    FOREIGN KEY (season, team_h) REFERENCES teams(season, id),
    FOREIGN KEY (season, team_a) REFERENCES teams(season, id)
);

CREATE TABLE players(
    season                                  TEXT NOT NULL,
    id                                      INTEGER NOT NULL,
    web_name                                TEXT NOT NULL,
    first_name                              TEXT NOT NULL,
    second_name                             TEXT NOT NULL,
    team                                    INTEGER NOT NULL,
    element_type                            INTEGER NOT NULL,
    status                                  TEXT,
    news                                    TEXT,
    chance_of_playing_next_round            INTEGER,
    now_cost                                INTEGER NOT NULL,
    selected_by_percent                     REAL,
    penalties_order                         INTEGER,
    corners_and_indirect_freekicks_order    INTEGER,
    direct_freekicks_order                  INTEGER,
    code                                    INTEGER,
    opta_code                               TEXT,
    ep_next                                 REAL,
    PRIMARY KEY (season, id),
    FOREIGN KEY (season, team) REFERENCES teams(season, id),
    FOREIGN KEY (element_type) REFERENCES positions(id)
);

CREATE TABLE gameweek_stats(
    season                                  TEXT NOT NULL,
    element                                 INTEGER NOT NULL,
    fixture                                 INTEGER NOT NULL,
    opponent_team                           INTEGER NOT NULL,
    total_points                            INTEGER,
    was_home                                INTEGER,
    kickoff_time                            TEXT,
    team_h_score                            INTEGER,
    team_a_score                            INTEGER,
    round                                   INTEGER NOT NULL,
    minutes                                 INTEGER,
    goals_scored                            INTEGER,
    assists                                 INTEGER,
    clean_sheets                            INTEGER,
    goals_conceded                          INTEGER,
    own_goals                               INTEGER,
    penalties_saved                         INTEGER,
    penalties_missed                        INTEGER,
    yellow_cards                            INTEGER,
    red_cards                               INTEGER,
    saves                                   INTEGER,
    bonus                                   INTEGER,
    bps                                     INTEGER,
    influence                               REAL,
    creativity                              REAL,
    threat                                  REAL,
    ict_index                               REAL,
    clearances_blocks_interceptions         INTEGER,
    recoveries                              INTEGER,
    tackles                                 INTEGER,
    defensive_contribution                  INTEGER,
    starts                                  INTEGER,
    expected_goals                          REAL,
    expected_assists                        REAL,
    expected_goal_involvements              REAL,
    expected_goals_conceded                 REAL,
    value                                   INTEGER NOT NULL,
    selected                                INTEGER,
    transfers_in                            INTEGER,
    transfers_out                           INTEGER,
    PRIMARY KEY (season, element, fixture),
    FOREIGN KEY (season, element) REFERENCES players(season, id),
    FOREIGN KEY (season, opponent_team) REFERENCES teams(season, id)
);
